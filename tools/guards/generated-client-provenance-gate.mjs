#!/usr/bin/env node
// Proves the provenance of every tracked file under a */clients/generated/
// directory, per VC-150 in
// tools/validclean-repository-reconstruction/10_REPOSITORY_WIDE_EXECUTION_LEDGER.md.
//
// Two things are enforced:
//   1. No orphans. Every file in a declared generated root is registered in
//      governance/contracts/generated-client-registry.json, and every registered
//      client exists. A file cannot enter or leave a generated directory silently.
//   2. Delete-regenerate-diff = 0 for OPENAPI_TYPESCRIPT entries. The committed
//      client must be byte-identical to a fresh openapi-typescript run against
//      its committed contract.
//
// HAND_AUTHORED_FACADE entries are NOT proven generated. They are reported as
// unproven with their owning slice so the count stays visible instead of being
// silently folded into a pass. Adding one requires a contract, an alignment
// test that exists, a reconstruction owner and a reason.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";

const repositoryRoot = path.resolve(new URL(".", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"), "..", "..");
const registryRelative = "governance/contracts/generated-client-registry.json";
const packageScripts = JSON.parse(fs.readFileSync(path.join(repositoryRoot, "package.json"), "utf8")).scripts ?? {};
const registry = JSON.parse(fs.readFileSync(path.join(repositoryRoot, registryRelative), "utf8"));

const failures = [];
const unproven = [];

const registered = new Map();
for (const entry of registry.entries) {
  if (registered.has(entry.client)) failures.push(`${registryRelative}: duplicate entry for ${entry.client}`);
  registered.set(entry.client, entry);
}

// 1. Orphan detection in both directions.
const ignored = new Set(registry.ignoredFiles ?? []);
for (const root of registry.generatedRoots) {
  const absoluteRoot = path.join(repositoryRoot, root);
  if (!fs.existsSync(absoluteRoot)) {
    failures.push(`${registryRelative}: declared generated root does not exist: ${root}`);
    continue;
  }
  for (const name of fs.readdirSync(absoluteRoot)) {
    if (ignored.has(name)) continue;
    const relative = `${root}/${name}`;
    if (!registered.has(relative)) {
      failures.push(`unregistered file in a generated directory: ${relative} — add it to ${registryRelative} or remove it`);
    }
  }
}

const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "bthwani-generated-client-provenance-"));

for (const [relativeClient, entry] of registered) {
  const clientPath = path.join(repositoryRoot, relativeClient);
  const contractPath = path.join(repositoryRoot, entry.contract);

  if (!fs.existsSync(clientPath)) {
    failures.push(`registered client is missing on disk: ${relativeClient}`);
    continue;
  }
  if (!fs.existsSync(contractPath)) {
    failures.push(`${relativeClient}: contract not found: ${entry.contract}`);
    continue;
  }
  if (!registry.generatedRoots.some((root) => relativeClient.startsWith(`${root}/`))) {
    failures.push(`${relativeClient} is registered but sits outside every declared generated root`);
  }

  if (entry.mode === "HAND_AUTHORED_FACADE") {
    for (const field of ["alignmentTest", "reconstructionOwner", "reason"]) {
      if (!entry[field]) failures.push(`${relativeClient}: HAND_AUTHORED_FACADE entry is missing required field '${field}'`);
    }
    if (entry.alignmentTest && !fs.existsSync(path.join(repositoryRoot, entry.alignmentTest))) {
      failures.push(`${relativeClient}: declared alignment test does not exist: ${entry.alignmentTest}`);
    }
    unproven.push(`${relativeClient} (owner ${entry.reconstructionOwner})`);
    continue;
  }

  if (entry.mode !== "OPENAPI_TYPESCRIPT") {
    failures.push(`${relativeClient}: unknown mode '${entry.mode}'`);
    continue;
  }

  if (!entry.regenerateScript || !packageScripts[entry.regenerateScript]) {
    failures.push(`${relativeClient}: regenerateScript '${entry.regenerateScript}' is not a root package.json script`);
  }

  const committed = fs.readFileSync(clientPath, "utf8");
  if (!/auto-generated by openapi-typescript/i.test(committed)) {
    failures.push(`${relativeClient} is missing the openapi-typescript provenance header`);
  }

  const outFile = path.join(tmpDir, relativeClient.replaceAll("/", "__"));
  const pnpm = process.platform === "win32" ? "pnpm.cmd" : "pnpm";
  // shell:true is required on Windows to invoke the pnpm.cmd shim (plain
  // spawnSync fails with EINVAL). All arguments are fixed, repo-internal paths
  // read from a committed registry -- never user or network input -- matching
  // the existing shell:true usage in tools/scripts/_external-tool-runner.mjs.
  const result = spawnSync(pnpm, ["exec", "openapi-typescript", contractPath, "--output", outFile], {
    cwd: repositoryRoot,
    encoding: "utf8",
    shell: process.platform === "win32",
  });
  if (result.error || result.status !== 0) {
    failures.push(`openapi-typescript failed for ${entry.contract}: ${result.error?.message ?? result.stderr ?? result.stdout ?? "unknown spawn failure"}`);
    continue;
  }

  if (fs.readFileSync(outFile, "utf8") !== committed) {
    failures.push(`${relativeClient} is stale relative to ${entry.contract}; run pnpm run ${entry.regenerateScript} and commit the result`);
  }
}

fs.rmSync(tmpDir, { recursive: true, force: true });

if (failures.length > 0) {
  console.error("generated-client-provenance-gate: FAILED");
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

const provenCount = [...registered.values()].filter((entry) => entry.mode === "OPENAPI_TYPESCRIPT").length;
console.log(`generated-client-provenance-gate: OK (${provenCount} clients byte-identical to source)`);
if (unproven.length > 0) {
  console.log(`generated-client-provenance-gate: ${unproven.length} hand-authored facade(s) NOT proven generated — reconstruction still owed:`);
  for (const item of unproven) console.log(`- ${item}`);
}
