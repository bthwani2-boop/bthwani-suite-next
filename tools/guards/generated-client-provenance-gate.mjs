#!/usr/bin/env node
// Proves the provenance of every materialized file under a */clients/generated/
// directory. Generated clients are deterministic build artifacts; canonical
// entry contracts, modules, overlays and manifests are the only tracked API truth.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawn } from "node:child_process";
import { resolvePackageManagerInvocation } from "../scripts/lib/package-manager-invocation.mjs";
import { generatedClientEntries } from "../scripts/contract-client-metadata.mjs";
import { generateGoTypesFromFile } from "../scripts/generate-openapi-go-types.mjs";

const repositoryRoot = path.resolve(new URL(".", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"), "..", "..");
const packageScripts = JSON.parse(fs.readFileSync(path.join(repositoryRoot, "package.json"), "utf8")).scripts ?? {};
const entries = generatedClientEntries();

const failures = [];
const requiredContexts = new Set(["identity", "workforce", "platform-control", "providers", "dsh", "wlt"]);
const supportedModes = new Set(["OPENAPI_TYPESCRIPT", "OPENAPI_GO"]);
const retiredHandAuthoredGeneratedRoots = [
  "services/wlt/frontend/shared/dsh/wlt/generated",
];

for (const retiredRoot of retiredHandAuthoredGeneratedRoots) {
  const absoluteRoot = path.join(repositoryRoot, retiredRoot);
  if (!fs.existsSync(absoluteRoot)) continue;
  const files = fs.readdirSync(absoluteRoot, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.join(entry.parentPath ?? retiredRoot, entry.name));
  for (const file of files) {
    failures.push(`${retiredRoot}: hand-authored generated residue is forbidden: ${file}`);
  }
}

const contexts = new Set(entries.map((entry) => entry.context));
if (contexts.size !== requiredContexts.size) {
  failures.push(`contract manifests: expected exactly ${requiredContexts.size} bounded contexts, found ${contexts.size}`);
}

const registered = new Map();
const generatedRoots = new Set();
for (const entry of entries) {
  if (!requiredContexts.has(entry.context)) failures.push(`${entry.manifest}: unexpected context '${entry.context}'`);
  if (registered.has(entry.client)) failures.push(`${entry.manifest}: duplicate generated client ${entry.client}`);
  registered.set(entry.client, entry);
  if (entry.scanRoot) generatedRoots.add(entry.generatedRoot);
}
for (const context of requiredContexts) if (!contexts.has(context)) failures.push(`contract manifests: missing bounded context '${context}'`);

const ignored = new Set([".gitkeep", "README.md"]);
for (const root of generatedRoots) {
  const absoluteRoot = path.join(repositoryRoot, root);
  if (!fs.existsSync(absoluteRoot)) {
    failures.push(`contract manifests: declared generated root does not exist after materialization: ${root}`);
    continue;
  }
  for (const name of fs.readdirSync(absoluteRoot)) {
    if (ignored.has(name)) continue;
    const relative = `${root}/${name}`;
    if (!registered.has(relative)) {
      failures.push(`unregistered file in a generated directory: ${relative} — declare the bounded-context client in its contract manifest or remove the artifact`);
    }
  }
}

const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "bthwani-generated-client-provenance-"));
const generationJobs = [];

for (const [relativeClient, entry] of registered) {
  const clientPath = path.join(repositoryRoot, relativeClient);
  const contractPath = path.join(repositoryRoot, entry.contract);

  if (!fs.existsSync(clientPath)) {
    failures.push(`generated client is missing after materialization: ${relativeClient}`);
    continue;
  }
  if (!fs.existsSync(contractPath)) {
    failures.push(`${relativeClient}: canonical bundle was not materialized: ${entry.contract}`);
    continue;
  }
  if (!relativeClient.startsWith(`${entry.generatedRoot}/`)) {
    failures.push(`${relativeClient} sits outside its manifest-derived generated root ${entry.generatedRoot}`);
  }

  if (!supportedModes.has(entry.mode)) {
    failures.push(`${relativeClient}: unsupported generated-client mode '${entry.mode}'`);
    continue;
  }

  const regenerateMatch = /^pnpm run ([A-Za-z0-9:_-]+)$/.exec(entry.regenerateScript ?? "");
  if (!regenerateMatch) {
    failures.push(`${relativeClient}: regenerateScript '${entry.regenerateScript}' must name one root pnpm script`);
  } else if (!packageScripts[regenerateMatch[1]]) {
    failures.push(`${relativeClient}: regenerateScript '${entry.regenerateScript}' does not resolve to a root package.json script`);
  }

  const materialized = fs.readFileSync(clientPath, "utf8");
  if (entry.mode === "OPENAPI_TYPESCRIPT") {
    if (!/auto-generated by openapi-typescript/i.test(materialized)) {
      failures.push(`${relativeClient} is missing the openapi-typescript provenance header`);
    }

    const outFile = path.join(tmpDir, relativeClient.replaceAll("/", "__"));
    const invocation = resolvePackageManagerInvocation(
      "pnpm",
      ["exec", "openapi-typescript", contractPath, "--output", outFile],
      process.env,
    );
    generationJobs.push({ relativeClient, contract: entry.contract, regenerateScript: entry.regenerateScript, materialized, outFile, invocation });
  } else {
    if (!/Code generated by tools\/scripts\/generate-openapi-go-types\.mjs/u.test(materialized)) {
      failures.push(`${relativeClient} is missing the generated Go provenance header`);
    }
    const generated = generateGoTypesFromFile(contractPath, entry.contract);
    if (materialized !== generated) failures.push(`${relativeClient} is stale relative to ${entry.contract}; rerun ${entry.regenerateScript}`);
  }
}

function generateClient(job) {
  return new Promise((resolve) => {
    const child = spawn(job.invocation.executable, job.invocation.args, {
      cwd: repositoryRoot,
      shell: false,
      windowsHide: true,
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    child.stdout?.on("data", (chunk) => { stdout += chunk; });
    child.stderr?.on("data", (chunk) => { stderr += chunk; });
    child.once("error", (error) => resolve({ job, error }));
    child.once("close", (status, signal) => resolve({ job, status, signal, stdout, stderr }));
  });
}

const generationResults = [];
let nextGeneration = 0;
async function generationWorker() {
  while (nextGeneration < generationJobs.length) {
    const job = generationJobs[nextGeneration];
    nextGeneration += 1;
    generationResults.push(await generateClient(job));
  }
}
await Promise.all(Array.from({ length: Math.min(3, generationJobs.length) }, () => generationWorker()));

for (const result of generationResults) {
  const { job } = result;
  if (result.error || result.status !== 0) {
    failures.push(`openapi-typescript failed for ${job.contract}: ${result.error?.message ?? result.stderr ?? result.stdout ?? (result.signal ? `signal ${result.signal}` : "unknown spawn failure")}`);
    continue;
  }
  if (fs.readFileSync(job.outFile, "utf8") !== job.materialized) {
    failures.push(`${job.relativeClient} is stale relative to ${job.contract}; rerun ${job.regenerateScript}`);
  }
}

fs.rmSync(tmpDir, { recursive: true, force: true });

if (failures.length > 0) {
  console.error("generated-client-provenance-gate: FAILED");
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

const provenCount = [...registered.values()].filter((entry) => supportedModes.has(entry.mode)).length;
console.log(`generated-client-provenance-gate: OK (${provenCount} materialized clients byte-identical to canonical bundles)`);
