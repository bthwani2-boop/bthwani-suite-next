#!/usr/bin/env node
// Proves every generated platform-control TypeScript client is byte-identical
// to a fresh `openapi-typescript` run against its committed source contract
// (delete-regenerate-diff = 0), per VC-150 in
// tools/validclean-repository-reconstruction/10_REPOSITORY_WIDE_EXECUTION_LEDGER.md.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";

const repositoryRoot = path.resolve(new URL(".", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"), "..", "..");

const pairs = [
  {
    contract: "core/platform-control/contracts/platform-control.openapi.yaml",
    client: "core/platform-control/clients/generated/platform-control-api.ts",
  },
  {
    contract: "core/platform-control/contracts/platform-change-sets.openapi.yaml",
    client: "core/platform-control/clients/generated/platform-change-sets-api.ts",
  },
  {
    contract: "core/platform-control/contracts/platform-progressive-rollout.openapi.yaml",
    client: "core/platform-control/clients/generated/platform-progressive-rollout-api.ts",
  },
];

const failures = [];
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "bthwani-platform-control-provenance-"));

for (const { contract, client } of pairs) {
  const contractPath = path.join(repositoryRoot, contract);
  const clientPath = path.join(repositoryRoot, client);

  if (!fs.existsSync(contractPath)) {
    failures.push(`missing contract: ${contract}`);
    continue;
  }
  if (!fs.existsSync(clientPath)) {
    failures.push(`missing generated client: ${client}`);
    continue;
  }

  const committed = fs.readFileSync(clientPath, "utf8");
  if (!/auto-generated by openapi-typescript/i.test(committed)) {
    failures.push(`${client} is missing the openapi-typescript provenance header`);
  }

  const outFile = path.join(tmpDir, path.basename(client));
  const pnpm = process.platform === "win32" ? "pnpm.cmd" : "pnpm";
  // shell:true is required on Windows to invoke the pnpm.cmd shim (plain
  // spawnSync fails with EINVAL). All arguments here are fixed, repo-internal
  // paths -- never derived from user or network input -- so this carries no
  // injection risk, matching the existing shell:true usage in
  // tools/scripts/_external-tool-runner.mjs and tools/scripts/run-zizmor.mjs.
  const result = spawnSync(pnpm, ["exec", "openapi-typescript", contractPath, "--output", outFile], {
    cwd: repositoryRoot,
    encoding: "utf8",
    shell: process.platform === "win32",
  });
  if (result.error || result.status !== 0) {
    failures.push(`openapi-typescript failed for ${contract}: ${result.error?.message ?? result.stderr ?? result.stdout ?? "unknown spawn failure"}`);
    continue;
  }

  const fresh = fs.readFileSync(outFile, "utf8");
  if (fresh !== committed) {
    failures.push(`${client} is stale relative to ${contract}; run pnpm run openapi:generate:platform-control (or the change-sets/progressive-rollout variant) and commit the result`);
  }
}

fs.rmSync(tmpDir, { recursive: true, force: true });

if (failures.length > 0) {
  console.error("platform-control-client-provenance-gate: FAILED");
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

console.log(`platform-control-client-provenance-gate: OK (${pairs.length} generated clients verified byte-identical to source)`);
