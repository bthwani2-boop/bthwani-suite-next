#!/usr/bin/env node
// Verifies deterministic, read-only OpenAPI composition for the four core
// bounded contexts owned by the generic composer. Generated bundles and clients
// are intentionally untracked build artifacts; their materialized byte-level
// provenance is owned centrally by generated-client-provenance-gate.mjs.
import { composeContext, contextManifests } from "../scripts/openapi-context-composer.mjs";
import {
  assertNoUnresolvedLocalOpenApiReferences,
} from "../scripts/openapi-composition-integrity.mjs";

const contexts = ["identity", "workforce", "platform-control", "providers"];
const failures = [];

for (const context of contexts) {
  if (!contextManifests[context]) {
    failures.push(`${context}: context manifest is not registered`);
    continue;
  }

  const first = await composeContext(context, { write: false });
  const second = await composeContext(context, { write: false });

  try {
    assertNoUnresolvedLocalOpenApiReferences(first.bundle, first);
    assertNoUnresolvedLocalOpenApiReferences(second.bundle, second);
  } catch (error) {
    failures.push(error instanceof Error ? error.message : String(error));
    continue;
  }
  if (first.bundle !== second.bundle) {
    failures.push(`${context}: composition is not deterministic`);
    continue;
  }
  if (first.sourceDigest !== second.sourceDigest) {
    failures.push(`${context}: source digest is not deterministic`);
    continue;
  }
  if (first.pathCount === 0) {
    failures.push(`${context}: composed bundle exposes no paths`);
    continue;
  }
  if (first.operationIds.length === 0) {
    failures.push(`${context}: composed bundle exposes no operations`);
    continue;
  }
  if (new Set(first.operationIds).size !== first.operationIds.length) {
    failures.push(`${context}: composed bundle contains duplicate operationIds`);
    continue;
  }
  if (!/^# AUTO-GENERATED by tools\/scripts\/compose-openapi-context\.mjs\. DO NOT EDIT\./.test(first.bundle)) {
    failures.push(`${context}: composed bundle is missing deterministic provenance`);
    continue;
  }
  if (!/x-bthwani-contract-layout:\s*COMPOSED_BUNDLE/.test(first.bundle)) {
    failures.push(`${context}: composed bundle is missing COMPOSED_BUNDLE layout metadata`);
    continue;
  }
  if (!/x-bthwani-source-sha256:\s*[a-f0-9]{64}/.test(first.bundle)) {
    failures.push(`${context}: composed bundle is missing its canonical source digest`);
    continue;
  }

  console.log(
    `openapi-bundle-provenance-gate: OK ${context} (${first.pathCount} paths, ${first.operationIds.length} operations, repositoryWrites=0)`,
  );
}

if (failures.length > 0) {
  console.error("openapi-bundle-provenance-gate: FAILED");
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}
