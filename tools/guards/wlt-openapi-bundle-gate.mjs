import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {
  composeContext,
  repositoryRoot,
} from "../scripts/openapi-context-composer.mjs";

const result = await composeContext("wlt", { write: false });
const committedBundle = fs.readFileSync(
  path.join(repositoryRoot, result.bundlePath),
  "utf8",
);
const generatedClientPath = path.join(
  repositoryRoot,
  "services/wlt/clients/generated/wlt-api.ts",
);
const generatedClient = fs.readFileSync(generatedClientPath, "utf8");

assert.equal(
  result.bundle,
  committedBundle,
  "WLT generated bundle is stale; run pnpm run openapi:generate:wlt",
);
assert.ok(result.pathCount > 0, "WLT composed bundle must expose paths");
assert.ok(result.operationIds.length > 0, "WLT composed bundle must expose operations");
assert.equal(
  new Set(result.operationIds).size,
  result.operationIds.length,
  "WLT composed bundle contains duplicate operationIds",
);
assert.match(
  generatedClient,
  /This file was auto-generated by openapi-typescript/,
  "WLT client must be generated by openapi-typescript",
);
for (const operationId of result.operationIds) {
  assert.ok(
    generatedClient.includes(operationId),
    `WLT generated client is missing operationId ${operationId}`,
  );
}

console.log(
  `WLT OpenAPI bundle gate passed: ${JSON.stringify({
    bundlePath: result.bundlePath,
    pathCount: result.pathCount,
    operationCount: result.operationIds.length,
    sourceDigest: result.sourceDigest,
  })}`,
);
