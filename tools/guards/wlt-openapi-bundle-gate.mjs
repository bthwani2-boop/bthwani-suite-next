import assert from "node:assert/strict";
import {
  composeContext,
} from "../scripts/openapi-context-composer.mjs";

// Generated-client provenance is owned centrally by
// generated-client-provenance-gate.mjs after deterministic materialization.
// This WLT-specific gate must remain read-only and runnable from a clean checkout.
const first = await composeContext("wlt", { write: false });
const second = await composeContext("wlt", { write: false });

assert.equal(
  first.bundle,
  second.bundle,
  "WLT OpenAPI composition must be deterministic without materializing generated artifacts",
);
assert.equal(
  first.sourceDigest,
  second.sourceDigest,
  "WLT OpenAPI source digest must be deterministic",
);
assert.ok(first.pathCount > 20, "WLT composed bundle must expose governed financial paths");
assert.ok(
  first.operationIds.length >= first.pathCount,
  "WLT composed bundle must preserve operation identifiers",
);
assert.equal(
  new Set(first.operationIds).size,
  first.operationIds.length,
  "WLT composed bundle contains duplicate operationIds",
);
assert.match(
  first.bundle,
  /^# AUTO-GENERATED by tools\/scripts\/compose-openapi-context\.mjs\. DO NOT EDIT\./,
  "WLT composed bundle must retain deterministic provenance",
);
assert.match(
  first.bundle,
  /x-bthwani-contract-layout:\s*COMPOSED_BUNDLE/,
  "WLT composed bundle must declare its generated layout",
);
assert.match(
  first.bundle,
  /x-bthwani-source-sha256:\s*[a-f0-9]{64}/,
  "WLT composed bundle must expose its source digest",
);
assert.doesNotMatch(
  first.bundle,
  /^x-bthwani-contracts:/m,
  "WLT composed bundle must not retain the source module index",
);

for (const operationId of [
  "createWltPaymentSession",
  "captureWltPaymentSession",
  "createWltRefund",
  "createWltEvidenceBackedSettlement",
  "createWltDestinationBoundPayoutRequest",
  "listWltLedgerEntries",
]) {
  assert.ok(
    first.operationIds.includes(operationId),
    `WLT composed bundle is missing governed operationId ${operationId}`,
  );
}
assert.ok(
  !first.operationIds.includes("appendWltLedgerEntry"),
  "direct ledger append must remain absent from the public WLT contract",
);

console.log(
  `WLT OpenAPI bundle gate passed: ${JSON.stringify({
    bundlePath: first.bundlePath,
    pathCount: first.pathCount,
    operationCount: first.operationIds.length,
    sourceDigest: first.sourceDigest,
    repositoryWrites: 0,
  })}`,
);