#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { generatedClientEntries } from "../scripts/contract-client-metadata.mjs";

const repositoryRoot = path.resolve(new URL(".", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"), "..", "..");
const failures = [];
const canonicalGenerated = "core/identity/clients/go/identityauth/contract.gen.go";
const canonicalBackendRoot = "core/identity/backend/";

const identityEntries = generatedClientEntries().filter((entry) => entry.context === "identity");
const goEntries = identityEntries.filter((entry) => entry.mode === "OPENAPI_GO");
if (goEntries.length !== 1 || goEntries[0]?.client !== canonicalGenerated) {
  failures.push(`identity contract: expected one OPENAPI_GO target at ${canonicalGenerated}`);
}

let generated = "";
if (!fs.existsSync(path.join(repositoryRoot, canonicalGenerated))) {
  failures.push(`identity contract: generated Go target is missing: ${canonicalGenerated}`);
} else {
  generated = fs.readFileSync(path.join(repositoryRoot, canonicalGenerated), "utf8");
  if (!/^\/\/ Code generated by tools\/scripts\/generate-openapi-go-types\.mjs from OpenAPI\. DO NOT EDIT\./m.test(generated)) {
    failures.push(`identity contract: generated Go target is missing its provenance header: ${canonicalGenerated}`);
  }
}
const wireTypes = new Set([...generated.matchAll(/^type\s+([A-Za-z_]\w*)\s+struct\b/gm)].map((match) => match[1]));
const sharedWireTypes = new Set([...wireTypes].filter((name) => name.endsWith("Error")));

const trackedGoFiles = execFileSync("git", ["ls-files", "--", "*.go"], {
  cwd: repositoryRoot,
  encoding: "utf8",
})
  .trim()
  .split(/\r?\n/)
  .filter(Boolean)
  .map((relative) => relative.replaceAll("\\", "/"));

for (const relative of trackedGoFiles) {
  if (relative === canonicalGenerated || relative.startsWith(canonicalBackendRoot)) continue;
  const source = fs.readFileSync(path.join(repositoryRoot, relative), "utf8");
  for (const match of source.matchAll(/^type\s+([A-Za-z_]\w*)\s+struct\b/gm)) {
    const typeName = match[1];
    if (wireTypes.has(typeName) && !sharedWireTypes.has(typeName)) {
      failures.push(`${relative}: manual Identity wire type ${typeName} is outside the canonical owner`);
    }
  }
}

for (const relative of trackedGoFiles.filter((file) =>
  file.startsWith("services/dsh/backend/internal/auth/") && !file.endsWith("_test.go"))) {
  const source = fs.readFileSync(path.join(repositoryRoot, relative), "utf8");
  if (/newDSHInternalRequest|rbacRequest|json\.(NewDecoder|Marshal)|http\.NewRequest|\bc\.(internalServiceToken|baseURL|http)\b/.test(source)) {
    failures.push(`${relative}: DSH facade still owns a duplicate Identity transport path`);
  }
}

if (failures.length > 0) {
  console.error("identity-contract-ownership-gate: FAILED");
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

console.log(`identity-contract-ownership-gate: PASS canonicalGo=${canonicalGenerated} trackedGo=${trackedGoFiles.length}`);
