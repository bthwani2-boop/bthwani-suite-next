import assert from 'node:assert/strict';
import { test } from 'node:test';
import { composeWltOpenApi } from './wlt-openapi-bundle-lib.mjs';

test('WLT composition resolves every indexed contract into one deterministic bundle', () => {
  const first = composeWltOpenApi({ write: false });
  const second = composeWltOpenApi({ write: false });

  assert.equal(first.bundle, second.bundle, 'composition must be deterministic');
  assert.ok(first.sourceFiles.length > 1, 'the WLT entry contract must index module contracts');
  assert.ok(first.pathCount > 20, 'the bundle must contain module paths, not only core paths');
  assert.ok(first.operationIds.length >= first.pathCount, 'the bundle must preserve operation identifiers');
  assert.match(first.bundle, /^# AUTO-GENERATED by tools\/scripts\/compose-wlt-openapi\.mjs\. DO NOT EDIT\./);
  assert.match(first.bundle, /x-bthwani-contract-layout: BUNDLED_GENERATED/);
  assert.match(first.bundle, /x-bthwani-source-digest: [a-f0-9]{64}/);
  assert.doesNotMatch(first.bundle, /^x-bthwani-contracts:/m);
});

test('WLT composition includes critical governed financial operations', () => {
  const result = composeWltOpenApi({ write: false });
  for (const operationId of [
    'createWltPaymentSession',
    'captureWltPaymentSession',
    'createWltRefund',
    'createWltEvidenceBackedSettlement',
    'createWltDestinationBoundPayoutRequest',
    'listWltLedgerEntries',
  ]) {
    assert.ok(result.operationIds.includes(operationId), `missing operationId ${operationId}`);
  }
  assert.ok(!result.operationIds.includes('appendWltLedgerEntry'), 'direct ledger append must remain absent');
});
