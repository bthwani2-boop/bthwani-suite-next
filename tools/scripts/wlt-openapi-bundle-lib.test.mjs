import assert from "node:assert/strict";
import { test } from "node:test";
import { composeContext } from "./openapi-context-composer.mjs";

test("WLT composition resolves its manifest into one deterministic bundle", async () => {
  const first = await composeContext("wlt", { write: false });
  const second = await composeContext("wlt", { write: false });

  assert.equal(first.bundle, second.bundle, "composition must be deterministic");
  assert.ok(first.pathCount > 20, "the WLT bundle must contain module paths");
  assert.ok(
    first.operationIds.length >= first.pathCount,
    "the WLT bundle must preserve operation identifiers",
  );
  assert.match(
    first.bundle,
    /^# AUTO-GENERATED by tools\/scripts\/compose-openapi-context\.mjs\. DO NOT EDIT\./,
  );
  assert.match(first.bundle, /x-bthwani-contract-layout: COMPOSED_BUNDLE/);
  assert.match(first.bundle, /x-bthwani-source-sha256: [a-f0-9]{64}/);
  assert.doesNotMatch(first.bundle, /^x-bthwani-contracts:/m);
});

test("WLT composition includes critical governed financial operations", async () => {
  const result = await composeContext("wlt", { write: false });
  for (const operationId of [
    "createWltPaymentSession",
    "captureWltPaymentSession",
    "createWltRefund",
    "createWltEvidenceBackedSettlement",
    "createWltDestinationBoundPayoutRequest",
    "listWltLedgerEntries",
  ]) {
    assert.ok(
      result.operationIds.includes(operationId),
      `missing operationId ${operationId}`,
    );
  }
  assert.ok(
    !result.operationIds.includes("appendWltLedgerEntry"),
    "direct ledger append must remain absent",
  );
});
