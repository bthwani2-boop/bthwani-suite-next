#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { composeAllContexts, repositoryRoot } from "./openapi-context-composer.mjs";
import { generatedClientEntries } from "./contract-client-metadata.mjs";
import { generateGoTypesFromFile } from "./generate-openapi-go-types.mjs";

const MATERIALIZATION_SCHEMA_VERSION = 3;
const OPENAPI_TYPESCRIPT_HEADER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;
const materializerPath = fileURLToPath(import.meta.url);
const composerPath = path.join(repositoryRoot, "tools/scripts/openapi-context-composer.mjs");
const clientMetadataPath = path.join(repositoryRoot, "tools/scripts/contract-client-metadata.mjs");
const goTypesGeneratorPath = path.join(repositoryRoot, "tools/scripts/generate-openapi-go-types.mjs");
const identityGoModulePath = path.join(repositoryRoot, "core/identity/clients/go/identityauth/go.mod");
const lockfilePath = path.join(repositoryRoot, "pnpm-lock.yaml");
const stampPath = path.join(repositoryRoot, ".artifacts/openapi/materialization.json");

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function sha256File(filePath) {
  return sha256(fs.readFileSync(filePath));
}

function normalizeText(value) {
  return String(value).replace(/\r\n/g, "\n");
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function readStamp() {
  if (!fs.existsSync(stampPath)) return undefined;
  try {
    return readJson(stampPath);
  } catch {
    return undefined;
  }
}

function artifactInventory(entries) {
  return [...new Set(
    entries.flatMap((entry) => [entry.contract, entry.client]),
  )].sort();
}

function currentArtifactHashes(relativePaths) {
  const hashes = {};
  for (const relativePath of relativePaths) {
    const absolutePath = path.join(repositoryRoot, relativePath);
    if (!fs.existsSync(absolutePath) || !fs.statSync(absolutePath).isFile()) return undefined;
    hashes[relativePath] = sha256File(absolutePath);
  }
  return hashes;
}

function sameHashes(expected, actual, relativePaths) {
  if (!expected || !actual) return false;
  return relativePaths.every((relativePath) => expected[relativePath] === actual[relativePath]);
}

function fail(message) {
  console.error(`openapi-materialization: FAIL ${message}`);
  process.exit(1);
}

function pinnedGoToolchainDigest() {
  const moduleSource = fs.readFileSync(identityGoModulePath, "utf8");
  const pinnedVersion = moduleSource.match(/^go\s+(\d+\.\d+\.\d+)\s*$/mu)?.[1];
  if (!pinnedVersion) fail("Identity Go module must declare an exact Go version for contract materialization");

  let actualVersion;
  try {
    actualVersion = execFileSync("go", ["env", "GOVERSION"], {
      cwd: repositoryRoot,
      encoding: "utf8",
      env: { ...process.env, GOTOOLCHAIN: "local" },
    }).trim();
  } catch (error) {
    fail(`pinned Go toolchain is unavailable: ${error.message}`);
  }
  if (actualVersion !== `go${pinnedVersion}`) {
    fail(`expected Go ${pinnedVersion}, found ${actualVersion || "unknown"}`);
  }
  return sha256(JSON.stringify({ pinnedVersion, actualVersion }));
}

function writeComposedBundles(composition) {
  for (const composed of composition) {
    const bundlePath = path.join(repositoryRoot, composed.bundlePath);
    fs.mkdirSync(path.dirname(bundlePath), { recursive: true });
    const bundle = normalizeText(
      composed.bundle.endsWith("\n") ? composed.bundle : `${composed.bundle}\n`,
    );
    fs.writeFileSync(bundlePath, bundle, "utf8");
  }
}

async function generateRegisteredClients(entries, composition) {
  const composedByContext = new Map(composition.map((entry) => [entry.context, entry]));

  for (const entry of entries) {
    if (!["OPENAPI_TYPESCRIPT", "OPENAPI_GO"].includes(entry.mode)) {
      fail(`unsupported generated-client mode ${String(entry.mode)} for ${entry.context}`);
    }

    const composed = composedByContext.get(entry.context);
    if (!composed) {
      fail(`manifest context ${entry.context} has no composed OpenAPI bundle`);
    }
    if (composed.bundlePath !== entry.contract) {
      fail(
        `manifest contract mismatch for ${entry.context}: expected ${composed.bundlePath}, got ${entry.contract}`,
      );
    }

    const contractPath = path.join(repositoryRoot, entry.contract);
    const clientPath = path.join(repositoryRoot, entry.client);
    if (!fs.existsSync(contractPath)) {
      fail(`missing materialized contract ${entry.contract}`);
    }

    fs.mkdirSync(path.dirname(clientPath), { recursive: true });
    if (entry.mode === "OPENAPI_TYPESCRIPT") {
      const ast = await openapiTS(pathToFileURL(contractPath));
      const body = normalizeText(astToString(ast));
      const generated = body.startsWith(OPENAPI_TYPESCRIPT_HEADER)
        ? body
        : `${OPENAPI_TYPESCRIPT_HEADER}${body}`;
      fs.writeFileSync(
        clientPath,
        generated.endsWith("\n") ? generated : `${generated}\n`,
        "utf8",
      );
    } else {
      fs.writeFileSync(clientPath, generateGoTypesFromFile(contractPath, entry.contract), "utf8");
    }
  }
}

const generatedClients = generatedClientEntries();
const composition = await composeAllContexts({ write: false });
const sourceDigests = Object.fromEntries(
  composition.map((result) => [result.context, result.sourceDigest]),
);
const bundleDigests = Object.fromEntries(
  composition.map((result) => [result.context, sha256(normalizeText(result.bundle))]),
);
const toolchainDigests = {
  materializer: sha256File(materializerPath),
  composer: sha256File(composerPath),
  clientMetadata: sha256File(clientMetadataPath),
  goTypesGenerator: sha256File(goTypesGeneratorPath),
  goToolchain: pinnedGoToolchainDigest(),
};
const clientMetadataDigest = sha256(JSON.stringify(generatedClients));
const materializationKey = sha256(JSON.stringify({
  schemaVersion: MATERIALIZATION_SCHEMA_VERSION,
  clientMetadataDigest,
  lockfileSha256: sha256File(lockfilePath),
  sourceDigests,
  bundleDigests,
  toolchainDigests,
}));
const relativeArtifacts = artifactInventory(generatedClients);
const currentHashes = currentArtifactHashes(relativeArtifacts);
const stamp = readStamp();

if (
  stamp?.schemaVersion === MATERIALIZATION_SCHEMA_VERSION &&
  stamp.materializationKey === materializationKey &&
  sameHashes(stamp.artifacts, currentHashes, relativeArtifacts)
) {
  console.log(`openapi-materialization: PASS mode=reuse contexts=${composition.length} artifacts=${relativeArtifacts.length}`);
  process.exit(0);
}

writeComposedBundles(composition);
await generateRegisteredClients(generatedClients, composition);

for (const composed of composition) {
  const bundlePath = path.join(repositoryRoot, composed.bundlePath);
  if (!fs.existsSync(bundlePath)) {
    fail(`missing materialized bundle ${composed.bundlePath}`);
  }
  const materialized = normalizeText(fs.readFileSync(bundlePath, "utf8"));
  const expected = normalizeText(composed.bundle.endsWith("\n") ? composed.bundle : `${composed.bundle}\n`);
  if (materialized !== expected) {
    fail(`${composed.context} bundle differs from deterministic composition`);
  }
}

const generatedHashes = currentArtifactHashes(relativeArtifacts);
if (!generatedHashes) fail("one or more generated artifacts are missing after materialization");

fs.mkdirSync(path.dirname(stampPath), { recursive: true });
fs.writeFileSync(stampPath, `${JSON.stringify({
  schemaVersion: MATERIALIZATION_SCHEMA_VERSION,
  materializationKey,
  clientMetadataDigest,
  sourceDigests,
  bundleDigests,
  toolchainDigests,
  artifacts: generatedHashes,
}, null, 2)}\n`, "utf8");

console.log(`openapi-materialization: PASS mode=regenerate contexts=${composition.length} artifacts=${relativeArtifacts.length}`);
